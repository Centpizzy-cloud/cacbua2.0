		<h2 class="section-num">4. Nigeria–China opportunity</h2>
		<p>Nigeria offers a concrete early picture of the policy's effect. According to Chinese Ambassador to Nigeria Yu Dunhai, Nigeria–China trade rose 35% to $18 billion in the first half of 2026 following the zero-tariff rollout. Chinese imports from Nigeria specifically surged 80% to $2.3 billion over the same period, with monthly growth in Nigerian exports to China exceeding 40% in both May and June — the first two months the policy was in effect.</p>
		<p>Chinese authorities have named sesame, cattle bone granules, and liquefied propane as specific Nigerian products benefiting from the tariff concessions, and Nigeria's aquatic products separately secured zero-tariff access under a new bilateral protocol.</p>
		<p>These figures describe national trade data, not CACBUA-facilitated trade — CACBUA has not organized or claimed credit for any of these transactions, and this brief does not imply otherwise.</p>

