		<h2 class="section-num">1. What changed in 2026?</h2>
		<p>On 14 February 2026, Chinese President Xi Jinping announced that China would grant zero-tariff treatment to all African countries holding diplomatic relations with China. This built on a policy already in place since 1 December 2024, which had eliminated tariffs on all tariff lines for Africa's 33 least-developed countries under the same diplomatic-recognition condition.</p>
		<p>The 2026 expansion extended zero-tariff treatment to a further 20 African countries not classified as least-developed. It took effect on 1 May 2026 and, per China's State Council, runs through 30 April 2028 for those 20 countries.</p>
		<p>Combined, the policy now covers 53 of the 54 African countries that hold diplomatic relations with China. Eswatini is the sole exclusion, as it maintains diplomatic ties with Taiwan rather than China.</p>
		<p>Government sources describe the change as applying to "all tariff lines" — meaning the removal is not limited to a specific product list. That breadth is precisely why Section 3, below, matters: a zero tariff rate does not by itself mean a product can freely enter the Chinese market.</p>

		<h2 class="section-num">2. Where could African businesses benefit?</h2>
		<div class="topic-grid">
			<article class="topic-card"><span class="num">01</span><h3>Agriculture &amp; processed food</h3><p>Products such as dried chilies, coffee, and cashews gained unified duty-free access under the policy.</p></article>
			<article class="topic-card"><span class="num">02</span><h3>High-value agricultural exports</h3><p>Nigeria's aquatic products, for example, separately secured zero-tariff access under a new bilateral protocol.</p></article>
			<article class="topic-card"><span class="num">03</span><h3>Manufacturing</h3><p>Producers assembling or processing goods in Africa may find new price competitiveness, though scale and certification requirements vary widely by sector.</p></article>
			<article class="topic-card"><span class="num">04</span><h3>Minerals &amp; value-added processing</h3><p>Tariff-free access may improve the economics of processing minerals in Africa rather than exporting them raw — subject to separate investment and infrastructure conditions.</p></article>
			<article class="topic-card"><span class="num">05</span><h3>Renewable-energy supply chains</h3><p>Components and materials feeding renewable-energy manufacturing may see improved market access, though this is a developing area, not an established trend.</p></article>
			<article class="topic-card"><span class="num">06</span><h3>Selected consumer products</h3><p>Nigerian goods including sesame, cattle bone granules, and liquefied propane are named by Chinese authorities as specific early beneficiaries.</p></article>
		</div>
		<p>These are illustrative categories, not guarantees. Not every product in a category automatically qualifies, and tariff-free treatment does not by itself guarantee commercial success — see Section 3.</p>

		<h2 class="section-num">3. Zero tariff does not mean zero barriers</h2>
